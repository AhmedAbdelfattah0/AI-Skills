// Behaviour test for the extraction command documented in session-restore/SKILL.md (Step 1).
// The command is read from SKILL.md itself and run against logs in the format session-logger writes.
// Run: node --test skills/session-restore/restore.test.mjs
import { test, describe, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const skillText = readFileSync(join(here, 'SKILL.md'), 'utf8');

const HEADER = '# Session Log\n\nAuto-generated by session-logger. Do not edit manually.\n\n';

function entry(stamp, goal, keyFiles = ['- src/a.ts - new']) {
  return [
    '---',
    `## Session: ${stamp}`,
    '',
    `**Goal:** ${goal}`,
    '',
    '**Completed:**',
    '- src/a.ts - created',
    '',
    '**Decisions:**',
    '- keep it simple - fewer moving parts',
    '',
    '**Deferred:**',
    '- nothing',
    '',
    '**Next Session Should:**',
    '- run the build',
    '',
    '**Key Files:**',
    ...keyFiles,
    '',
  ].join('\n');
}

// The documented command: the awk line(s) inside the fenced bash block.
function documentedCommands() {
  const block = /```bash\n([\s\S]*?)```/.exec(skillText);
  assert.ok(block, 'SKILL.md has a fenced bash block');
  return block[1].split('\n').filter((line) => line.startsWith('awk '));
}

// Output contract: starts at the last entry's "## Session:" heading, ends at its last content
// line (trailing separators and blank lines dropped), one trailing newline.
const body = (text) => text.replace(/^---\n/, '');

describe('session-restore Step 1 extraction command', { skip: process.platform === 'win32' && 'needs POSIX sh and awk' }, () => {
  let dir;
  let command;

  before(() => {
    const found = documentedCommands();
    assert.equal(found.length, 1, 'exactly one awk line is documented in the bash block');
    command = found[0];
    dir = mkdtempSync(join(tmpdir(), 'restore-test-'));
  });

  after(() => {
    if (dir) rmSync(dir, { recursive: true, force: true });
  });

  function run(logText) {
    writeFileSync(join(dir, 'session-log.md'), logText);
    const result = spawnSync('sh', ['-c', command], { cwd: dir, encoding: 'utf8' });
    assert.equal(result.error, undefined, 'the command spawned');
    assert.equal(result.status, 0, `command exited 0 (stderr: ${result.stderr})`);
    return result.stdout;
  }

  test('two-entry log returns the second entry and not the first', () => {
    const out = run(HEADER + entry('2026-03-23 10:00', 'FIRST-GOAL-MARKER') + entry('2026-03-24 14:30', 'SECOND-GOAL-MARKER'));
    assert.ok(out.includes('## Session: 2026-03-24 14:30'), `second heading missing from: ${JSON.stringify(out)}`);
    assert.ok(out.includes('SECOND-GOAL-MARKER'), `second goal missing from: ${JSON.stringify(out)}`);
    assert.ok(!out.includes('FIRST-GOAL-MARKER'), 'first entry must not be returned');
  });

  test('log ending in a closing separator still returns the last entry', () => {
    const out = run(HEADER + entry('2026-03-23 10:00', 'FIRST-GOAL-MARKER') + entry('2026-03-24 14:30', 'SECOND-GOAL-MARKER') + '---\n');
    assert.ok(out.includes('## Session: 2026-03-24 14:30'), `last heading missing from: ${JSON.stringify(out)}`);
    assert.ok(out.includes('SECOND-GOAL-MARKER'), `last goal missing from: ${JSON.stringify(out)}`);
    assert.ok(!out.includes('FIRST-GOAL-MARKER'), 'first entry must not be returned');
  });

  test('single-entry log returns that entry', () => {
    const out = run(HEADER + entry('2026-03-24 14:30', 'ONLY-GOAL-MARKER'));
    assert.ok(out.includes('## Session: 2026-03-24 14:30'), `heading missing from: ${JSON.stringify(out)}`);
    assert.ok(out.includes('ONLY-GOAL-MARKER'), `goal missing from: ${JSON.stringify(out)}`);
  });

  test('two-entry log prints exactly the last entry, from heading to last content line', () => {
    const last = entry('2026-03-24 14:30', 'SECOND-GOAL-MARKER');
    const out = run(HEADER + entry('2026-03-23 10:00', 'FIRST-GOAL-MARKER') + last);
    assert.equal(out, body(last));
  });

  test('last entry quoting a diff keeps its heading, goal and both diff lines', () => {
    const last = entry('2026-03-24 14:30', 'DIFF-GOAL-MARKER', ['- --- a/src/x.ts', '--- a/src/x.ts', '+++ b/src/x.ts']);
    const out = run(HEADER + entry('2026-03-23 10:00', 'FIRST-GOAL-MARKER') + last);
    assert.equal(out, body(last));
    assert.ok(out.includes('--- a/src/x.ts') && out.includes('+++ b/src/x.ts'));
  });

  test('last entry containing a horizontal rule keeps the text after the rule', () => {
    const last = entry('2026-03-24 14:30', 'RULE-GOAL-MARKER', ['- before the rule', '---', '- AFTER-RULE-MARKER']);
    const out = run(HEADER + entry('2026-03-23 10:00', 'FIRST-GOAL-MARKER') + last);
    assert.equal(out, body(last));
  });

  for (const count of [2, 3]) {
    test(`log ending in ${count} separator lines returns the last entry`, () => {
      const last = entry('2026-03-24 14:30', 'MANY-SEP-GOAL-MARKER');
      const out = run(HEADER + entry('2026-03-23 10:00', 'FIRST-GOAL-MARKER') + last + '---\n'.repeat(count));
      assert.equal(out, body(last));
    });
  }

  test('log with no session heading prints nothing', () => {
    assert.equal(run(HEADER), '');
  });
});
